import platform
import re
import sys

import build
import extension_helper
import fs_utils
import src

if sys.platform == 'linux':
    xcb_headers = ('xcb.h', 'xcbext.h')
    stubs_hpp = fs_utils.generated_dir / 'xcb_host_stubs.hpp'
    stubs_cpp = fs_utils.generated_dir / 'xcb_host_stubs.cpp'

    def core_functions():
        names = []
        for header in xcb_headers:
            text = (build.PREFIX / 'include' / 'xcb' / header).read_text()
            text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
            names += re.findall(r'\b(xcb_\w+)\s*\((?:[^()]|\([^()]*\))*\)\s*;', text)
        return names

    def stub(index, name):
        if platform.machine() == 'aarch64':
            return [f'  .globl {name}',
                    f'  .type {name}, @function',
                    f'{name}:',
                    f'  adrp x16, xcb_host_table+{8 * index}',
                    f'  ldr x16, [x16, :lo12:xcb_host_table+{8 * index}]',
                    '  br x16',
                    f'.Lmissing_{index}:',
                    f'  mov w0, #{index}',
                    '  b AbortOnMissingHostXcbFunction',
                    f'  .size {name}, . - {name}']
        return [f'  .globl {name}',
                f'  .type {name}, @function',
                f'{name}:',
                f'  jmp *xcb_host_table+{8 * index}(%rip)',
                f'.Lmissing_{index}:',
                f'  mov ${index}, %edi',
                '  jmp AbortOnMissingHostXcbFunction',
                f'  .size {name}, . - {name}']

    def generate_stubs():
        names = core_functions()
        stubs_hpp.write_text('\n'.join([
            '// Generated by src/xcb.py from xcb.h and xcbext.h.',
            '#pragma once',
            '',
            'extern "C" {',
            '',
            'extern const char* const xcb_host_names[];',
            'extern void* xcb_host_table[];',
            '',
            '}  // extern "C"',
            '']))
        cpp = ['// Generated by src/xcb.py from xcb.h and xcbext.h.',
               '#include "xcb_host_stubs.hpp"',
               '',
               'const char* const xcb_host_names[] = {']
        cpp += [f'    "{name}",' for name in names]
        cpp += ['    nullptr,', '};', '', 'asm(R"(', '  .pushsection .text']
        for index, name in enumerate(names):
            cpp += stub(index, name)
        cpp += ['  .popsection',
                '  .pushsection .data',
                '  .balign 8',
                '  .globl xcb_host_table',
                'xcb_host_table:']
        cpp += [f'  .quad .Lmissing_{index}' for index in range(len(names))]
        cpp += ['  .popsection', ')");', '']
        stubs_cpp.write_text('\n'.join(cpp))

    def hook_srcs(srcs, recipe):
        recipe.add_step(generate_stubs,
                        [stubs_hpp, stubs_cpp],
                        [__file__, *libxcb.outputs],
                        desc='Generating the host libxcb stubs',
                        shortcut='xcb-host-stubs')
        for path in (stubs_hpp, stubs_cpp):
            recipe.generated.add(str(path))
        srcs[str(stubs_hpp)] = src.File(stubs_hpp)
        stubs_cpp_file = src.File(stubs_cpp)
        stubs_cpp_file.direct_includes.append(str(stubs_hpp))
        srcs[str(stubs_cpp)] = stubs_cpp_file

